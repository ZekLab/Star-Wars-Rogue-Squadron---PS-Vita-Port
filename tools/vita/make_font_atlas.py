#!/usr/bin/env python3
"""Generates src/vita_gfx/vg_font.inl: an alpha atlas of printable ASCII for the Vita renderer's text overlay.

Uses Pillow's built-in font (Aileron Regular, SIL Open Font License), so no font file is needed.
Usage: python3 tools/vita/make_font_atlas.py [size]
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

SIZE = int(sys.argv[1]) if len(sys.argv) > 1 else 24
FIRST, LAST = 32, 126
COLUMNS = 16
PAD = 2

font = ImageFont.load_default(size=SIZE)
ascent, descent = font.getmetrics()
cell_h = ascent + descent + PAD * 2
glyphs = []
cell_w = 0
for code in range(FIRST, LAST + 1):
    left, top, right, bottom = font.getbbox(chr(code))
    cell_w = max(cell_w, right - min(left, 0) + PAD * 2)
    glyphs.append((code, left, right, font.getlength(chr(code))))

rows = (len(glyphs) + COLUMNS - 1) // COLUMNS
width, height = COLUMNS * cell_w, rows * cell_h
atlas = Image.new("L", (width, height), 0)
draw = ImageDraw.Draw(atlas)
entries = []
for i, (code, left, right, advance) in enumerate(glyphs):
    cx, cy = (i % COLUMNS) * cell_w, (i // COLUMNS) * cell_h
    draw.text((cx + PAD - min(left, 0), cy + PAD), chr(code), font=font, fill=255)
    entries.append((cx, cy, advance))

out = os.path.join(os.path.dirname(__file__), "..", "..", "src", "vita_gfx", "vg_font.inl")
with open(out, "w") as f:
    f.write("// Generated by tools/vita/make_font_atlas.py (Pillow's built-in Aileron Regular, SIL Open Font License). Do not edit.\n")
    f.write(f"constexpr int FontFirst = {FIRST}, FontLast = {LAST};\n")
    f.write(f"constexpr int FontAtlasWidth = {width}, FontAtlasHeight = {height};\n")
    f.write(f"constexpr int FontCellWidth = {cell_w}, FontCellHeight = {cell_h}, FontPad = {PAD}, FontAscent = {ascent};\n")
    f.write("// Per glyph: cell x, cell y in the atlas, advance in pixels.\n")
    f.write("constexpr float FontGlyphs[][3] = {\n")
    for cx, cy, advance in entries:
        f.write(f"    {{ {cx}.0f, {cy}.0f, {advance:.2f}f }},\n")
    f.write("};\n")
    f.write("constexpr unsigned char FontAtlas[] = {\n")
    data = atlas.tobytes()
    for i in range(0, len(data), 32):
        f.write("    " + ", ".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n")
print(f"wrote {out}: atlas {width}x{height}, cell {cell_w}x{cell_h}")
